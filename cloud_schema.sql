-- Badakhshan App - Supabase setup
-- Run this once in Supabase SQL Editor.
-- The Streamlit app uses the server-side service-role key, so these tables
-- can keep Row Level Security enabled without public read/write policies.

create table if not exists public.registrations (
    id bigint generated by default as identity primary key,
    name text not null,
    district text,
    occupation text,
    phone text,
    email text,
    message text,
    created_at timestamptz not null default now()
);

create table if not exists public.contacts (
    id bigint generated by default as identity primary key,
    name text not null,
    district text,
    occupation text,
    phone text,
    email text,
    subject text,
    message text,
    created_at timestamptz not null default now()
);

create table if not exists public.submissions (
    id bigint generated by default as identity primary key,
    kind text not null,
    category text,
    title_en text,
    title_fa text,
    body_en text,
    body_fa text,
    filename text,
    stored_path text,
    status text not null default 'pending',
    submitted_by text,
    created_at timestamptz not null default now(),
    reviewed_at timestamptz
);

create table if not exists public.audit (
    id bigint generated by default as identity primary key,
    action text,
    detail text,
    created_at timestamptz not null default now()
);

alter table public.registrations enable row level security;
alter table public.contacts enable row level security;
alter table public.submissions enable row level security;
alter table public.audit enable row level security;

-- Private storage bucket for user uploads.
insert into storage.buckets (id, name, public)
values ('badakhshan-uploads', 'badakhshan-uploads', false)
on conflict (id) do nothing;

-- No public policies are created. The app uses SUPABASE_SERVICE_ROLE_KEY
-- only on the server side for database/storage operations.
